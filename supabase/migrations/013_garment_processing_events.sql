-- Durable, user-visible diagnostics for asynchronous garment processing.
-- Edge Functions write through the service role; clients can only read events
-- belonging to their own garments.

CREATE TABLE IF NOT EXISTS garment_processing_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  garment_id UUID REFERENCES garments(id) ON DELETE CASCADE NOT NULL,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  attempt INTEGER NOT NULL DEFAULT 0 CHECK (attempt >= 0),
  stage TEXT NOT NULL CHECK (
    stage IN (
      'accepted',
      'claimed',
      'background_removal',
      'cutout_upload',
      'cutout_cache',
      'vision',
      'embedding',
      'save',
      'ready',
      'failed'
    )
  ),
  status TEXT NOT NULL CHECK (
    status IN ('started', 'succeeded', 'failed', 'skipped', 'info')
  ),
  message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 500),
  details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (
    jsonb_typeof(details) = 'object'
  ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_garment_processing_events_garment
  ON garment_processing_events(garment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_garment_processing_events_user
  ON garment_processing_events(user_id, created_at DESC);

ALTER TABLE garment_processing_events ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'garment_processing_events'
      AND policyname = 'Users can view own garment processing events'
  ) THEN
    CREATE POLICY "Users can view own garment processing events"
      ON garment_processing_events
      FOR SELECT
      USING (
        auth.uid() = user_id
        AND EXISTS (
          SELECT 1
          FROM garments
          WHERE garments.id = garment_processing_events.garment_id
            AND garments.user_id = auth.uid()
        )
      );
  END IF;
END;
$$;

REVOKE INSERT, UPDATE, DELETE
  ON garment_processing_events
  FROM anon, authenticated;
GRANT SELECT ON garment_processing_events TO authenticated;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'garment_processing_events'
  ) THEN
    ALTER PUBLICATION supabase_realtime
      ADD TABLE garment_processing_events;
  END IF;
END;
$$;

COMMENT ON TABLE garment_processing_events IS
  'Sanitized stage-by-stage diagnostics for garment enrichment attempts.';
